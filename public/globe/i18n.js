  let lang = "en";
  try { lang = localStorage.getItem("etd-lang") || (navigator.language || "en").slice(0, 2); } catch (e) { /* storage blocked */ }
  if (!STRINGS[lang]) lang = "en";

  function t(key, vars) {
    let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
    return s;
  }
  // Values computed from the data (set by app.js at load) fill any {key} a call does not pass.
  const defaults = {};
  function caseText(id, field, vars) {
    const c = CASE_TEXT[id];
    let s = (c && (c[lang] || c.en)[field]) || "";
    const all = { ...defaults[id], ...vars };
    s = s.replace(/\{(\w+)\}/g, (m, k) => (all[k] ?? m));
    return s;
  }
  const setCaseDefaults = (id, vars) => { defaults[id] = { ...defaults[id], ...vars }; };
